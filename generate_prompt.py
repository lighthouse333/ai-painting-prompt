def add_title(text, level=0):
    h = doc.add_heading(text, level=level)
    for run in h.runs:
        run.font.name = '微软雅黑'
    return h

def add_field(label, value):
    p = doc.add_paragraph()
    r1 = p.add_run(label)
    r1.bold = True
    r1.font.name = '微软雅黑'
    r1.font.size = Pt(11)
    r2 = p.add_run(value)
    r2.font.name = '微软雅黑'
    r2.font.size = Pt(11)
    return p

def add_note(text):
    p = doc.add_paragraph()
    r = p.add_run(f"⚠ {text}")
    r.font.name = '微软雅黑'
    r.font.size = Pt(10)
    r.font.color.rgb = RGBColor(180, 80, 80)
    return p

def add_checkbox(text):
    p = doc.add_paragraph(f"☑ {text}")
    for run in p.runs:
        run.font.name = '微软雅黑'
    return p

